// Vendors the three.js runtime + a classic-script GLTFLoader into web/vendor so the browser build
// works offline and the game can load .glb car models without a bundler.
// Usage: node tools/build-vendor.js      (run from the repo root, after `npm install` in desktop/)
const fs = require('fs'), path = require('path');

const root = path.join(__dirname, '..');
const threePkg = path.join(root, 'desktop', 'node_modules', 'three');
const out = path.join(root, 'web', 'vendor');
if (!fs.existsSync(threePkg)) {
  console.error('three.js not found in desktop/node_modules — run: cd desktop && npm install');
  process.exit(1);
}
fs.mkdirSync(out, { recursive: true });

// 1. the renderer itself
fs.copyFileSync(path.join(threePkg, 'build', 'three.min.js'), path.join(out, 'three.min.js'));

// 2. three r149 only ships ESM example loaders, so flatten the import/export syntax to a classic script
const MODULES = [
  path.join(threePkg, 'examples', 'jsm', 'utils', 'BufferGeometryUtils.js'),
  path.join(threePkg, 'examples', 'jsm', 'loaders', 'GLTFLoader.js'),
];
const deps = new Set();
const bodies = MODULES.map(file => {
  let src = fs.readFileSync(file, 'utf8');
  src = src.replace(/import\s*\{([^}]*)\}\s*from\s*['"]three['"];?/g, (_, names) => {
    names.split(',').map(s => s.trim()).filter(Boolean).forEach(n => deps.add(n.replace(/\s+as\s+.*/, '')));
    return '';
  });
  src = src.replace(/import\s*\{[^}]*\}\s*from\s*['"][^'"]+\.js['"];?/g, '');   // sibling helper modules, inlined below
  src = src.replace(/^export\s*\{[^}]*\};?$/gm, '');
  src = src.replace(/^export\s+/gm, '');
  return `\n// ---- ${path.basename(file)} ----\n` + src;
});

const banner = `// GENERATED by tools/build-vendor.js from three@${JSON.parse(fs.readFileSync(path.join(threePkg, 'package.json'))).version}
// Exposes THREE.GLTFLoader as a classic script so the game can load .glb models without a bundler.
`;
fs.writeFileSync(path.join(out, 'GLTFLoader.js'),
  banner + '(function () {\n"use strict";\nconst { ' + [...deps].sort().join(', ') + ' } = THREE;\n' + bodies.join('\n') + '\nTHREE.GLTFLoader = GLTFLoader;\n})();\n');

for (const f of ['three.min.js', 'GLTFLoader.js'])
  console.log('web/vendor/' + f, (fs.statSync(path.join(out, f)).size / 1024).toFixed(0) + ' KB');
