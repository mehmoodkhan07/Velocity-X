// Emits a CLASSIC-script bundle of the TypeScript rules so the browser game can use them with a
// plain <script> tag (no module loader, no async race with the rest of the game).
// Node's built-in type stripper is used, so there is no toolchain and no extra dependency.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { stripTypeScriptTypes } from 'node:module';

const here = path.dirname(fileURLToPath(import.meta.url));
const SRC = ['src/index.ts', 'src/daily.ts', 'src/gameplay.ts', 'src/input.ts'];
const out = path.join(here, '..', '..', 'web', 'vendor', 'game-core.js');

const names = new Set();
// `export const A = 1, B = 2;` exports every declarator, so collect the identifier of each one.
function addNames(decl) {
  let depth = 0, quote = 0, cur = '';
  const flush = () => {
    const n = (cur.match(/^\s*([A-Za-z_$][\w$]*)/) || [])[1];
    if (n) names.add(n);   // `= value` is ignored: only the declared identifier matters
    cur = '';
  };
  for (let i = 0; i < decl.length; i++) {
    const ch = decl[i], nx = decl[i + 1];
    if (quote) { if (ch === quote) quote = 0; cur += ch; continue; }
    if (ch === '"' || ch === "'" || ch === '`') quote = ch;
    else if (ch === '/' && nx === '/') break;                    // a trailing comment is not a declarator
    else if ('([{'.includes(ch)) depth++;
    else if (')]}'.includes(ch)) depth--;
    if (ch === ',' && depth === 0) flush(); else cur += ch;
  }
  flush();
}

const body = SRC.map(file => stripTypeScriptTypes(fs.readFileSync(path.join(here, file), 'utf8'), { mode: 'strip' })
  .replace(/^export\s+(?:async\s+)?function\s+([A-Za-z_$][\w$]*)/gm, (_, n) => { names.add(n); return 'function ' + n; })
  .replace(/^export\s+(const|let|var)\s+([^\n]+)/gm, (_, kw, decl) => { addNames(decl); return kw + ' ' + decl; })
  .replace(/^export\s+\{[^}]*\};?$/gm, '')
  .replace(/^export\s+default\s+/gm, ''))
  .join('\n');

// fail loudly instead of shipping a bundle with un-stripped module syntax
const leftover = body.match(/^.*\bexport\b.*$/m);
if (leftover) {
  console.error('game-core/build: un-stripped export left in the bundle -> ' + leftover[0].trim());
  process.exit(1);
}

const bundle =
  '// GENERATED by packages/game-core/build.js — edit the TypeScript sources instead.\n' +
  '// Classic script: the shared race rules are exposed as window.VXCORE.\n' +
  'window.VXCORE = (function () {\n' +
  body +
  '\nreturn { ' + [...names].sort().join(', ') + ' };\n})();\n';

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, bundle);

// Never ship a bundle that silently omits a rule: evaluate it and check every export really is there.
const api = vm.runInNewContext(bundle, { window: {} });
const missing = [...names].filter(n => api[n] === undefined);
if (missing.length) {
  console.error('game-core/build: exported name(s) missing from the bundle -> ' + missing.join(', '));
  process.exit(1);
}
console.log('game-core -> ' + path.relative(process.cwd(), out) + ' (' + fs.statSync(out).size + ' bytes, ' + names.size + ' exports)');
